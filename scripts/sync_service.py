"""Copy the shared feature code and the exported model into service/.

service/core/features.py is generated from src/hotel_cancellation/rowlevel.py;
tests/parity/test_service_sync.py fails if the two ever differ.
"""

from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ("# GENERATED by scripts/sync_service.py from src/hotel_cancellation/rowlevel.py. Do not edit.\n"
          "# Run `make sync-service` after changing the feature code.\n")


def main() -> None:
    source = (ROOT / "src" / "hotel_cancellation" / "rowlevel.py").read_text(encoding="utf-8")
    (ROOT / "service" / "core" / "features.py").write_text(HEADER + source, encoding="utf-8")
    export = ROOT / "artifacts" / "export"
    for name in ("model.onnx", "metadata.json"):
        if not (export / name).exists():
            raise SystemExit(f"missing {export / name}: run `make pipeline` (or the export stage) first")
        shutil.copy2(export / name, ROOT / "service" / "models" / name)
    print("service synced: core/features.py, models/model.onnx, models/metadata.json")


if __name__ == "__main__":
    main()
