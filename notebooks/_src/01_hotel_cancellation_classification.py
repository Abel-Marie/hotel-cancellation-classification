# ## 4. Algorithm selection
#
# This is **supervised** learning (every booking has a known outcome) and **binary classification**, on
# tabular data with a mix of numeric and categorical features, about 60,000 training rows and a moderate
# class imbalance. Candidates, from simplest to most flexible:
#
# | Model | Complexity | Interpretability | Compute cost | Why consider it |
# |---|---|---|---|---|
# | Majority-class baseline | None | Total | None | The floor every model must beat |
# | Logistic regression | Low | High: one coefficient per feature | Very low | Strong, honest linear baseline |
# | Decision tree | Medium | High for a shallow tree | Low | Readable rules, but unstable |
# | Random forest | High | Medium (importances) | Medium; large model files | Robust non-linear baseline |
# | HistGradientBoosting | High | Medium | Low | Fast boosting in scikit-learn |
# | LightGBM | High | Medium, explained with SHAP | Low | Usually strongest on tabular data |
# | Small neural network (MLP) | High | Low | Medium | Covers the neural-network family |
#
# **Not chosen, and why.** *Unsupervised* methods (K-Means, PCA) have no target to learn from; PCA is used
# for exploration only (3.5). *Reinforcement learning* does not fit: there is no sequence of actions and
# rewards, just one prediction per booking. Among supervised methods, support vector machines and
# k-nearest neighbours scale poorly to 60,000 rows with one-hot features and give no calibrated
# probability; deep networks have no advantage on a table of 30 columns and would be harder to explain
# and to deploy.
#
# **Deployment constraint.** The API runs on a serverless platform with a size limit, so the deployed
# model must be small and convertible to ONNX. Tree ensembles convert well; that is one reason the
# champion is chosen among tree models. The measured fit time, scoring time and model size of every
# candidate are in the table in Section 5.

