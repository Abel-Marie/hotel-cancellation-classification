# ### 10.5 Retraining policy
#
# Monitoring is only useful if it triggers action. The policy below turns the measurements into rules.

# %%
line = diag["val_metrics"]["roc_auc"] - 0.03
below = (by_month["roc_auc"] < line).to_numpy()
two_in_a_row = bool((below[1:] & below[:-1]).any())
say(f"""
| Signal | How it is measured | Action |
|---|---|---|
| **Performance drop** | Monthly ROC-AUC on bookings whose outcome is now known, from the feedback endpoint | Retrain if it falls more than 0.03 below the validation ROC-AUC ({diag['val_metrics']['roc_auc']:.3f}) for two months in a row |
| **Input drift** | Monthly PSI of every feature against the training data | Investigate any PSI above 0.25; retrain if three or more booking-channel or price features exceed it |
| **Calibration** | Average predicted probability against the actual cancellation rate each month | Re-fit the calibration (cheap, no retraining) if they differ by more than 5 percentage points |
| **Scheduled** | Calendar | Retrain at least every six months with the latest 24 months of bookings, so every season is represented |
| **Service health** | 95th-percentile latency and error rate from the logs | Alert if the 95th percentile exceeds 1 s or errors exceed 1% |

Applied to the check in 10.3 (a model trained on arrivals up to {temporal['eval_year'] - 1}, scored on
{temporal['eval_year']}), {int(below.sum())} of the {len(by_month)} months fall below that line ({line:.3f}),
{'including two in a row, so the performance rule would have called for retraining' if two_in_a_row else 'never two in a row, so the performance rule would not have fired'}.
The line comes from a random split, which is an optimistic reference for a model used on a later year;
that is exactly the situation the rule is there to catch.
Retraining means re-running this notebook (or the pipeline) on the newer data: the champion, calibration
and threshold are re-chosen, the parity check must pass, and the new model replaces the old one only if it
is at least as good on the newest validation period.
""")

