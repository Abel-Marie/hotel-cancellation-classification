# ### 3.7 What the duplicates really do to the score
#
# It is tempting to say that keeping duplicates inflates the score *because the model memorises copies*.
# That is only part of it, and the difference matters for how the final result should be read. The
# experiment below keeps the duplicates and scores the same model three ways (training and validation
# bookings only; every row that shares its booking-time inputs with a test booking is removed first):
#
# 1. **Random split:** copies of a booking can sit on both sides. This is what a careless pipeline does.
# 2. **Grouped split, every row scored:** all rows with identical booking-time inputs stay on one side,
#    so nothing can be memorised, but a booking that appears ten times still counts ten times.
# 3. **Grouped split, one row per distinct record:** the same predictions, each distinct record counted once.

# %%
