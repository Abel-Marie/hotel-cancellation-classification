# ### 8.3 The deployed API
#
# The FastAPI service in the repository's `service/` folder is built for Vercel's free tier (a serverless
# cloud platform); its address is the `service.url` setting in the configuration and is
# printed below. It runs the shared feature code, the ONNX model and the calibration, and returns the
# probability, a yes/no decision at the chosen threshold and a risk band. Interactive documentation is at
# `/docs` and a demo page at `/`.
#
# | Endpoint | Purpose |
# |---|---|
# | `GET /` | Demo page |
# | `GET /health` | Liveness and model version |
# | `GET /api/v1/model` | Model card: features, threshold, test metrics, excluded columns |
# | `POST /api/v1/predict` | One booking in, cancellation risk out |
# | `POST /api/v1/predict/batch` | Up to 100 bookings |
# | `POST /api/v1/feedback` | Report the real outcome of an earlier prediction |
# | `GET /api/v1/feedback/summary` | How the predictions compare with the outcomes reported so far |
# | `GET /api/v1/metrics` | Request counts and latency for the serving instance |
#
# **Integration with an existing system.** A hotel's booking system would call `POST /api/v1/predict`
# with the booking as JSON when the booking is created, store the returned probability and
# `prediction_id` next to the reservation, and report the real outcome to `/api/v1/feedback` once the
# arrival date has passed. The demo page is itself such a client: it calls the API from the browser in
# exactly this way. The cell below is another: plain Python, standard library only.

