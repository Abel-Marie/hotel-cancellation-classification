import json
import urllib.request

SERVICE_URL = os.environ.get("SERVICE_URL", cfg.service.url).rstrip("/")


def call_api(path: str, body: dict | None = None, timeout: float = 30.0) -> dict:
    """GET (no body) or POST (JSON body) to the deployed API and return the parsed reply."""
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(SERVICE_URL + path, data=data, headers={"Content-Type": "application/json"},
                                 method="GET" if body is None else "POST")
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read())


def api_reachable() -> bool:
    if not SERVICE_URL:
        return False
    try:
        return call_api("/health", timeout=20).get("status") == "ok"
    except Exception:  # noqa: BLE001 - any failure means "not reachable"
        return False


