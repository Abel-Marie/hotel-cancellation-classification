# ## 1. Problem definition
#
# **The business problem.** Hotels lose revenue when a booked room is cancelled too late to resell it.
# Revenue managers protect against this by overbooking, but overbooking blind is risky: if more guests
# arrive than there are rooms, the hotel must relocate ("walk") a guest to another hotel, paying for the
# room, transport and lost goodwill. A reliable estimate of each booking's cancellation risk lets the hotel
# overbook where it is safe and, for risky bookings, ask for a deposit or confirm with the guest.
#
# **The task.** Supervised binary classification. Target: `is_canceled` (1 = cancelled, 0 = the guest arrived).
#
# **The prediction moment is the day the booking is made.** Only information known at that moment may be
# a feature. This single decision drives the whole leakage audit in Section 3.6: any column that is filled
# in or changed later, for example at check-in, would let the model see the future.
#
# **How the prediction is used.** Two ways, and they need different things from the model:
#
# 1. *One booking at a time:* flag a booking and act on it (count the room as likely to come free, ask for
#    a deposit, send a confirmation request). This needs a **threshold**, and the right threshold depends
#    on what a wrong flag costs.
# 2. *Many bookings together:* add up the probabilities of all bookings for a hotel and week to get the
#    expected number of cancellations, which is what an overbooking level is set from. This needs
#    **calibrated probabilities**, not a threshold.
#
# **Two kinds of error, with different costs.**
#
# | Error | What happens | Cost in this project |
# |---|---|---|
# | Missed cancellation (false negative) | The room stays empty | 1 room-night |
# | False alarm (false positive) | The hotel overbooks, the guest arrives, someone is relocated | 2 room-nights |
#
# These costs are an assumption, stated in the configuration before modelling. They decide the operating
# threshold in Section 6.3; changing them changes the threshold, not the model, and Section 6.3 shows how
# the decision moves when they change.
#
# **Success criteria, fixed before any modelling:**

# %%
